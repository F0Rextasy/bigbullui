import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { collectAllIcons, toPascal } from "./lib/icon-extract.mjs";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = path.join(rootDir, "packages", "icons", "src");
const outFile = path.join(iconsDir, "named-icons.tsx");
const checkOnly = process.argv.includes("--check");

const icons = collectAllIcons(iconsDir);
const blocks = [];
const seenExports = new Set();

for (const [iconName, inner] of icons) {
  const componentName = `${toPascal(iconName)}Icon`;
  if (seenExports.has(componentName)) {
    throw new Error(`generate-icon-components: duplicate PascalCase icon export "${componentName}" from "${iconName}"`);
  }
  seenExports.add(componentName);
  blocks.push(
    `export function ${componentName}({ size = 20, ...props }: StampNamedIconProps) {\n` +
      `  return (\n` +
      `    <svg\n` +
      `      width={size}\n` +
      `      height={size}\n` +
      `      viewBox="0 0 24 24"\n` +
      `      fill="none"\n` +
      `      stroke="currentColor"\n` +
      `      strokeWidth="1.8"\n` +
      `      strokeLinecap="round"\n` +
      `      strokeLinejoin="round"\n` +
      `      aria-hidden={props["aria-hidden"] ?? (props["aria-label"] || props["aria-labelledby"] ? undefined : true)}\n` +
      `      {...props}\n` +
      `    >\n` +
      `      ${inner}\n` +
      `    </svg>\n` +
      `  );\n` +
      `}`
  );
}

const nextContent = (
  `// AUTO-GENERATED by scripts/generate-icon-components.mjs — DO NOT EDIT.\n` +
  `import * as React from "react";\n\n` +
  `export interface StampNamedIconProps extends Omit<React.SVGAttributes<SVGSVGElement>, "name"> {\n` +
  `  size?: number;\n` +
  `}\n\n` +
  blocks.join("\n\n") +
  "\n"
).replace(/\r\n/g, "\n");

if (checkOnly) {
  const existing = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8").replace(/\r\n/g, "\n") : "";
  if (existing !== nextContent) {
    console.error("generate-icon-components: packages/icons/src/named-icons.tsx is out of date. Run `node scripts/generate-icon-components.mjs`.");
    process.exit(1);
  }
  console.log(`generate-icon-components: ${icons.size} named icon components verified.`);
} else {
  fs.writeFileSync(outFile, nextContent);
  console.log(`generate-icon-components: ${icons.size} named icon components written to packages/icons/src/named-icons.tsx`);
}
